#!/usr/bin/env node
// Builds web/synth/pattern-prelude.js from app/web/pattern/*.
//
// Why a build step at all: the browser can only fetch what is under app/web/web/, and the sources belong in app/web/pattern/
// (the same arrangement this repository already uses for generated data: scripts/*.mjs writing into web/). The artifact is
// the only new file in the served root.
//
// Two things it does deliberately:
//
//   * the library is split into top-level units. The runtime's mruby compiler traps inside prism at roughly forty kilobytes
//     of program (a file of nothing but comments reproduces it) and library.rb is ninety-three, so it can never be loaded as
//     one program.
//   * --check regenerates into memory and compares byte for byte, so a stale artifact fails the gate instead of shipping.
//     This repository has already been bitten by a build output that aged silently.
//
//   node scripts/build-pattern.mjs           write web/synth/pattern-prelude.js
//   node scripts/build-pattern.mjs --check   compare, exit 1 if it differs
import fs from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const SRC = path.join(ROOT, "pattern");
const OUT = path.join(ROOT, "web/pattern/pattern-prelude.js");
const OUT_BOOT = path.join(ROOT, "web/pattern/pattern-boot.js");
const OUT_SESSION = path.join(ROOT, "web/pattern/session-run.js");

const read = (name) => fs.readFileSync(path.join(SRC, name), "utf8");
const stripLoads = (src) => src.split("\n").filter((l) => !/^\s*require_relative\b/.test(l) && !/^\s*require\s+["']/.test(l)).join("\n");

// The same rule the tests were split by, and it is checked: anything that is not a top-level module or class body would
// silently straddle two chunks.
const unitsOf = (src, name) => {
  const lines = stripLoads(src).split("\n");
  const starts = [];
  lines.forEach((l, i) => { if (/^(module|class) [A-Z]/.test(l)) starts.push(i); });
  if (!starts.length) throw new Error(`${name} has no top-level units, which cannot be right`);
  // A preamble before the first module/class is allowed only if it is comments and blanks: it rides with the first unit.
  // Anything executable up there would run before the library exists, which is a silent ordering fault, so it is refused.
  const preamble = lines.slice(0, starts[0]);
  const executable = preamble.filter((l) => l.trim().length && !/^\s*#/.test(l));
  if (executable.length) throw new Error(`${name} has executable code before its first module/class: ${executable[0].trim().slice(0, 60)}`);
  const units = [];
  for (let k = 0; k < starts.length; k++) {
    const from = k === 0 ? 0 : starts[k];
    units.push(lines.slice(from, k + 1 < starts.length ? starts[k + 1] : lines.length).join("\n"));
  }
  return units.filter((u) => u.trim().length);
};

const shim = read("shim.rb").trim();
const prelude = read("prelude.rb").trim();
const loader = read("loader.js").trim();
const boot = read("pattern-boot.js").trim();
const sessionRun = read("session-run.js").trim();
// library.rb holds the operators that need no Sonic Pi; runtime.rb holds the rest of the documented surface (pply, pzoom,
// psegment, pval, psine, ...). Each is split by its own top-level constructs and the labels are built from the same arrays,
// so chunks and files cannot disagree again.
const libChunks = unitsOf(read("library.rb"), "library.rb");
const runtimeChunks = unitsOf(read("runtime.rb"), "runtime.rb");
const libUnits = [...libChunks, ...runtimeChunks];

const chunks = [shim, ...libUnits, prelude];
const files = ["shim.rb",
  ...libChunks.map((_, i) => `library.rb [unit ${i + 1}/${libChunks.length}]`),
  ...runtimeChunks.map((_, i) => `runtime.rb [unit ${i + 1}/${runtimeChunks.length}]`),
  "prelude.rb"];

const artifact = `// GENERATED by scripts/build-pattern.mjs -- do not edit. Source: app/web/pattern/*.
// ${chunks.length} chunks: the shim, the library in ${libUnits.length} top-level units, the scheduler.
export const META = ${JSON.stringify({ generatedBy: "scripts/build-pattern.mjs", files, libraryUnits: libUnits.length }, null, 1)};

export const CHUNKS = [
${chunks.map((c) => "  " + JSON.stringify(c) + ",").join("\n")}
];

${loader}
`;

const bootFile = `// GENERATED by scripts/build-pattern.mjs -- do not edit. Source: app/web/pattern/pattern-boot.js.
${boot}
`;
const sessionFile = `// GENERATED by scripts/build-pattern.mjs -- do not edit. Source: app/web/pattern/session-run.js.
${sessionRun}
`;

const check = process.argv.includes("--check");
if (check) {
  if (!fs.existsSync(OUT)) { console.error(`  ${path.relative(ROOT, OUT)} is missing; run node scripts/build-pattern.mjs`); process.exit(1); }
  const now = fs.readFileSync(OUT, "utf8");
  const nowBoot = fs.existsSync(OUT_BOOT) ? fs.readFileSync(OUT_BOOT, "utf8") : "";
  const nowSession = fs.existsSync(OUT_SESSION) ? fs.readFileSync(OUT_SESSION, "utf8") : "";
  if (now !== artifact || nowBoot !== bootFile || nowSession !== sessionFile) {
    console.error(`  ${path.relative(ROOT, OUT)} is stale: app/web/pattern/ has changed since it was built`);
    process.exit(1);
  }
  console.log(`  ${path.relative(ROOT, OUT)} and pattern-boot.js are up to date (${chunks.length} chunks, ${libUnits.length} library units)`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, artifact);
fs.writeFileSync(OUT_BOOT, bootFile);
fs.writeFileSync(OUT_SESSION, sessionFile);
// The dev server serves build/web, and the layer silently ran a stale copy of itself more than once because only web/ was
// written: whichever of the two exists gets the artifacts, so "wrote" means "served".
  // Two data files decide what the editor offers: completion.json (docs, usage, opt ranges) and reference/lang.json, whose
  // keys ARE the function suggestions -- api.js builds keywords.Func from ref.lang.map(p => p.key). A pattern primitive therefore
  // needs a page in both, and the build puts it there so nothing in the editor knows the layer exists.
  for (const dir of [path.join(ROOT, "web/data/reference"), path.join(ROOT, "build/web/data/reference")]) {
    const file = path.join(dir, "lang.json");
    if (!fs.existsSync(file)) continue;
    const { completion: entries } = await import(pathToFileURL(path.join(ROOT, "pattern/completion.js")).href);
    const doc = JSON.parse(fs.readFileSync(file, "utf8"));   // {pages:[{key, summary, usage, doc_html}]}, not an array
    const pages = doc.pages;
    let changed = 0;
    for (const [name, e] of Object.entries(entries)) {
      const page = { key: name, title: e.summary ?? name, doc_html: e.doc ?? "", usage: e.usage ?? "" };
      const at = pages.findIndex((q) => q.key === name);
      if (at >= 0) {
        if (JSON.stringify(pages[at]) !== JSON.stringify({ ...pages[at], ...page })) { pages[at] = { ...pages[at], ...page }; changed++; }
      } else { pages.push(page); changed++; }
    }
    if (changed) {
      fs.writeFileSync(file, JSON.stringify(doc));
      console.log(`  reference: ${changed} pattern pages into ${path.relative(ROOT, file)}`);
    }
  }

  // The editors's completion list is data (web/data/completion.json), so the pattern primitives join it there: no editor code
  // needs to know the layer exists. Idempotent: entries are replaced by name, and the file is rewritten only when it differs.
  for (const dir of [path.join(ROOT, "web/data"), path.join(ROOT, "build/web/data")]) {
    const file = path.join(dir, "completion.json");
    if (!fs.existsSync(file)) continue;
    const { completion } = await import(pathToFileURL(path.join(ROOT, "pattern/completion.js")).href);
    const data = JSON.parse(fs.readFileSync(file, "utf8"));
    data.entries = data.entries || {};
    let changed = 0;
    for (const [name, entry] of Object.entries(completion)) {
      if (JSON.stringify(data.entries[name]) !== JSON.stringify(entry)) { data.entries[name] = entry; changed++; }
    }
    if (changed) {
      fs.writeFileSync(file, JSON.stringify(data));
      console.log(`  completion: ${changed} pattern entries into ${path.relative(ROOT, file)}`);
    }
  }

// The two app files this project patches (SP-EXT) must reach the served copy as well, or the browser runs the old code: that
// happened with pdeclared, which the served sonic_pi.js still called prun, and the library's own prun(n) answered
// "Run 的数量必须是正整数（给了 :end）". Only files that exist and differ are copied.
for (const rel of ["sonic_pi.js"]) {
  const from = path.join(ROOT, "web", rel);
  const to = path.join(ROOT, "build/web", rel);
  if (!fs.existsSync(from) || !fs.existsSync(path.dirname(to))) continue;
  const want = fs.readFileSync(from, "utf8");
  if (fs.existsSync(to) && fs.readFileSync(to, "utf8") === want) continue;
  fs.writeFileSync(to, want);
  console.log(`  synced web/${rel} -> build/web/${rel} (the served copy)`);
}

// Both runtime modules get the Stop shim, every build: the source copy and the one the dev server serves.
for (const dir of [ROOT, path.join(ROOT, "build/web")]) {
  if (ensureRuntimeShim(dir)) console.log(`  runtime shim -> ${path.relative(ROOT, dir) || "."}/runtime/sp_runtime.js`);
}
for (const extra of [path.join(ROOT, "build/web/pattern")]) {
  if (!fs.existsSync(path.dirname(extra))) continue;
  fs.mkdirSync(extra, { recursive: true });
  for (const [name, body] of [["pattern-prelude.js", artifact], ["pattern-boot.js", bootFile], ["session-run.js", sessionFile]]) {
    fs.writeFileSync(path.join(extra, name), body);
  }
  console.log(`  also wrote ${path.relative(ROOT, extra)}/ (the served copy)`);
}
console.log(`  wrote ${path.relative(ROOT, OUT)}: ${chunks.length} chunks, ${libUnits.length} library units, ${artifact.length} bytes`);
console.log(`  wrote ${path.relative(ROOT, OUT_BOOT)}: ${bootFile.length} bytes`);
